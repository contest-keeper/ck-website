// Writes public/THIRD-PARTY-LICENSES.txt: the licence text of every package whose code or fonts end up in
// the built site (the Svelte runtime and the self-hosted fonts, with what they depend on). Build tools such as
// vite are not part of the site and are not listed. Runs before every build (see "prebuild").
import { execFileSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

// Run through the same pnpm that runs this script.
const pnpm = process.env.npm_execpath;
if (!pnpm) {
  console.error('Run this with: pnpm run prebuild');
  process.exit(1);
}
const listing = JSON.parse(
  execFileSync(process.execPath, [pnpm, 'licenses', 'list', '--json'], { encoding: 'utf8', maxBuffer: 64 << 20 }),
);

const known = new Map();
for (const [license, packages] of Object.entries(listing)) {
  for (const p of packages) known.set(p.name, { ...p, license, path: p.paths[0] });
}

// What the built site contains: the roots and everything they depend on at run time.
const ROOTS = ['svelte', '@fontsource-variable/inter', '@fontsource-variable/manrope'];
const wanted = new Map();
const queue = [...ROOTS];
while (queue.length) {
  const name = queue.shift();
  if (wanted.has(name)) continue;
  const p = known.get(name);
  if (!p) {
    console.error(`No licence information for ${name}`);
    process.exit(1);
  }
  wanted.set(name, p);
  const manifest = JSON.parse(readFileSync(join(p.path, 'package.json'), 'utf8'));
  queue.push(...Object.keys(manifest.dependencies ?? {}));
}

const out = [
  'Contest Keeper website: third-party licences',
  '=============================================',
  '',
  'The site is licensed under the Apache License 2.0. It contains the packages below, each used under the licence shown.',
  'Generated by site/scripts/licences.mjs.',
  '',
];
for (const [name, p] of [...wanted].sort(([a], [b]) => a.localeCompare(b))) {
  const file = readdirSync(p.path).find((f) => /^(licen[cs]e|copying)/i.test(f));
  out.push('='.repeat(78), `${name} ${p.versions.join(', ')}  (${p.license})`, '='.repeat(78), '');
  out.push(file && existsSync(join(p.path, file)) ? readFileSync(join(p.path, file), 'utf8').trim() : `Licence: ${p.license}`);
  out.push('');
}
writeFileSync(new URL('../public/THIRD-PARTY-LICENSES.txt', import.meta.url), out.join('\n'));
console.log(`Wrote THIRD-PARTY-LICENSES.txt for ${wanted.size} packages`);
